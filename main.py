MODEL = "llama3.1:8b" # Depending on how your hardware is, you can change the model by pulling a ollama model in your regular terminal

# -----------------------
# File Reader
# -----------------------

def read_file(filename):
    try:
        with open(filename, "r", encoding="utf-8") as file:
            return file.read()

    except FileNotFoundError:
        return ""

# -----------------------
# Load Files
# -----------------------

personality = read_file("persona.txt")
memory = read_file("memory.txt")
commands = read_file("commands.txt")


# -----------------------
# System Prompt
# -----------------------

def create_system_prompt():
    return f"""
You are {ai_name}, an AI assistant.

PERSONALITY:
{personality}

MEMORY:
{memory}

COMMANDS:
{commands}

Use these files when responding to the user.
"""


system_prompt = create_system_prompt()


# -----------------------
# Start Eugene
# -----------------------
print(powerimg)
print(eugeneai_watermark)
print("\nType 'exit' to quit.")


# -----------------------
# Main Loop
# -----------------------
while True:
    user_message = input("\nYou: ")
    command = user_message.lower().strip()

    # -----------------------
    # Exit
    # -----------------------
    if command == "exit":
        print(f"{ai_name}: cya.\n")
        break

    # -----------------------
    # Remember Something
    # -----------------------
    if command.startswith("remember "):
        memory_text = user_message[len("remember "):].strip()
        if not memory_text:
            print(f"{ai_name}: What would you like me to remember?")
        elif memory_text in memory:
            print(f"{ai_name}: Memory is already stored.")
        else:
            store_memory(memory_text)
            memory += "\n" + memory_text
            system_prompt = create_system_prompt()
        continue

    # -----------------------
    # Forget Something
    # -----------------------
    if command.startswith("forget "):
        forget_memory_text = user_message[len("forget "):].strip()
        if not forget_memory_text:
            print(f"{ai_name}: What would you like me to forget?")
        else:
            if forget_memory(forget_memory_text):
                memory = memory.replace(forget_memory_text, "")
                system_prompt = create_system_prompt()
        continue

    # -----------------------
    # Normal Commands
    # -----------------------

    for command_name, command_function in sorted(
        COMMANDS.items(),
        key=lambda item: len(item[0]),
        reverse=True
    ):
        if command == command_name.lower():
            command_function()
            break

        elif command.startswith(command_name.lower() + " "):
            argument = user_message[len(command_name):].strip()
            command_function(argument)
            break

    else:
        # -----------------------
        # Send Message to Ollama
        # -----------------------
        try:
            response = ollama.chat(
                model=MODEL,
                messages=[
                    {
                        "role": "system",
                        "content": system_prompt
                    },
                    {
                        "role": "user",
                        "content": user_message
                    }
                ]
            )

            print(f"\n{ai_name}:", response["message"]["content"])
        except Exception as e:

            print(f"Error with model: {e}")
